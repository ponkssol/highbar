-- 0009: user referral rewards funded ONLY from the platform's swap-referral income (BUILD_BRIEF section 5 / 7).
-- Income = the referral fee the Meteora DBC program pays to REFERRAL_WALLET's WSOL account on Higher Bar swaps
-- (20% of Meteora's protocol fee, ~0.04% of curve volume). Nothing comes from the platform fee share. Idempotent (IF NOT EXISTS).

-- Referral fee of a via_ui swap, from the swap event (lamports). NULL = indexed before this column existed: the job then
-- derives it as REFERRAL_FEE_BPS_OF_TRADE_FEE (400 bps) of fee_sol.
ALTER TABLE trades ADD COLUMN IF NOT EXISTS referral_fee_lamports BIGINT;

-- Referral income generated by the referrer's referees in the period (what the reward is scaled from).
ALTER TABLE referral_rewards ADD COLUMN IF NOT EXISTS referral_fee_lamports BIGINT NOT NULL DEFAULT 0;

-- One row per closed period: what the referral wallet received and how it was allocated.
-- Locked (never rewritten) once a later period exists or any of the period's rewards is pending / paid.
CREATE TABLE IF NOT EXISTS referral_income (
  period TEXT PRIMARY KEY,
  period_start BIGINT NOT NULL,
  period_end BIGINT NOT NULL,
  income_lamports BIGINT NOT NULL,
  trades INT NOT NULL,
  derived_trades INT NOT NULL,
  attributable_lamports BIGINT NOT NULL,
  reward_bps INT NOT NULL,
  carry_in_lamports BIGINT NOT NULL,
  budget_lamports BIGINT NOT NULL,
  allocated_lamports BIGINT NOT NULL,
  carry_out_lamports BIGINT NOT NULL,
  unallocated_lamports BIGINT NOT NULL,
  referrers INT NOT NULL,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL,
  CHECK (income_lamports >= 0 AND carry_in_lamports >= 0 AND allocated_lamports >= 0 AND carry_out_lamports >= 0 AND unallocated_lamports >= 0),
  CHECK (allocated_lamports + carry_out_lamports + unallocated_lamports = income_lamports + carry_in_lamports)
);