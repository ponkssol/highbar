// ---- step 8: user referral + milestone bonus (apps/api jobs, /referral page) ----
import { BPS, CREATOR_TRADING_FEE_PCT, CURVE_FEE_BPS, METEORA_PROTOCOL_SHARE_PCT, type TierId } from "./index.js";

/** User referral program, funded ONLY from the platform's swap-referral income: the referral fee the Meteora DBC program pays to
 *  REFERRAL_WALLET's WSOL account on curve swaps built by Higher Bar (REFERRAL_SHARE_OF_PROTOCOL = 20% of Meteora's protocol fee,
 *  about 0.04% of volume). Nothing comes from the platform's fee share (40/50/10 is untouched).
 *  rewardBps = share of the referral income generated by a referrer's referees that is passed on to them (10000 = all of it).
 *  Env overrides in apps/api: REFERRAL_REWARD_BPS (max 10000), REFERRAL_MIN_PAYOUT_SOL. */
export const REFERRAL_DEFAULTS = { rewardBps: 10_000, minPayoutSol: 0.001 } as const;
/** Referral fee as bps of a curve trade's total fee: 20% protocol x 20% referral = 400 bps (4% of the fee). */
// Literal on purpose: index.ts re-exports this module, so its constants are not initialised yet at load time (fees.test checks it).
export const REFERRAL_FEE_BPS_OF_TRADE_FEE = 400;
/** Referral fee (lamports) inside a curve trade's total fee; only used for trades indexed before the swap event's referral_fee was stored. */
export const referralFeeFromTradeFee = (feeLamports: bigint) => (feeLamports * BigInt(REFERRAL_FEE_BPS_OF_TRADE_FEE)) / BigInt(BPS);

export interface ReferralSource { referrer: string; volume: bigint; referralFee: bigint }
export interface ReferralPlan {
  income: bigint; carryIn: bigint; attributable: bigint; budget: bigint; allocated: bigint; carryOut: bigint; unallocated: bigint;
  rows: (ReferralSource & { amount: bigint })[];
}
/** One epoch of the referral pool.
 *  - available = income received this epoch (referral fees of all Higher Bar swaps) + carryIn (rounding dust of earlier epochs).
 *  - budget = min(available, attributable x rewardBps + carryIn), where attributable = referral fees generated by referred wallets' trades.
 *    So a referrer is never paid out of income their referees did not generate, and the total can never exceed what was received.
 *  - each referrer gets floor(budget x their referees' curve volume / total referred volume).
 *  - carryOut = rounding dust (budget - allocated), added to the next epoch. unallocated = income not attributable to referred trades
 *    (or beyond rewardBps); it stays in the referral wallet and is not carried over.
 *  Invariant: allocated + carryOut + unallocated = income + carryIn. */
export function planReferralPool(o: { income: bigint; carryIn?: bigint; sources: ReferralSource[]; rewardBps?: number }): ReferralPlan {
  const carryIn = o.carryIn ?? 0n, bps = BigInt(Math.max(0, Math.min(BPS, Math.floor(o.rewardBps ?? REFERRAL_DEFAULTS.rewardBps))));
  if (o.income < 0n || carryIn < 0n) throw new Error("referral income / carry must be >= 0");
  const sources = o.sources.filter((s) => s.volume > 0n);
  const attributable = sources.reduce((a, s) => a + s.referralFee, 0n), volume = sources.reduce((a, s) => a + s.volume, 0n);
  const available = o.income + carryIn;
  let budget = (attributable * bps) / BigInt(BPS) + carryIn;
  if (budget > available) budget = available;
  const rows = volume > 0n ? sources.map((s) => ({ ...s, amount: (budget * s.volume) / volume })).filter((r) => r.amount > 0n) : [];
  const allocated = rows.reduce((a, r) => a + r.amount, 0n);
  return { income: o.income, carryIn, attributable, budget, allocated, carryOut: budget - allocated, unallocated: available - budget, rows };
}
/** ?ref=<wallet> link parameter and the localStorage key the web app keeps it under until the wallet signs in. */
export const REFERRAL_PARAM = "ref";

/** Platform share (lamports) of a curve trade fee for a tier (fee model helper; the referral program no longer uses it). `feeLamports` = total trading fee (0 -> estimated from volume at CURVE_FEE_BPS). */
export function platformFeeLamports(tier: TierId, feeLamports: bigint, volumeLamports = 0n): bigint {
  const fee = feeLamports > 0n ? feeLamports : (volumeLamports * BigInt(CURVE_FEE_BPS)) / BigInt(BPS);
  const afterProtocol = (fee * BigInt(100 - METEORA_PROTOCOL_SHARE_PCT)) / 100n;
  return (afterProtocol * BigInt(100 - (CREATOR_TRADING_FEE_PCT[tier] ?? 50))) / 100n;
}

/** Milestone bonus: the treasury pays the creator `rewardSol` once their token's market cap (SOL) stays at or above `mcapSol`
 *  for `days` consecutive full UTC days after migration. Override with MILESTONES="id:mcapSol:days:rewardSol,..." in apps/api. */
export interface Milestone { id: string; mcapSol: number; days: number; rewardSol: number }
export const MILESTONE_DEFAULTS: Milestone[] = [
  { id: "hold-1k-7d", mcapSol: 1_000, days: 7, rewardSol: 1 },
  { id: "hold-5k-30d", mcapSol: 5_000, days: 30, rewardSol: 5 },
];

/** "id:mcapSol:days:rewardSol,..." -> milestones (throws on a malformed entry). Empty -> defaults. */
export function parseMilestones(spec?: string | null): Milestone[] {
  if (!spec || !spec.trim()) return MILESTONE_DEFAULTS;
  const out = spec.split(",").map((s) => s.trim()).filter(Boolean).map((s) => {
    const [id, m, d, r] = s.split(":").map((x) => x.trim());
    const mcapSol = Number(m), days = Number(d), rewardSol = Number(r);
    if (!id || !/^[a-z0-9-]{1,32}$/i.test(id) || !(mcapSol > 0) || !Number.isInteger(days) || days < 1 || days > 365 || !(rewardSol >= 0))
      throw new Error(`bad milestone "${s}" (use id:mcapSol:days:rewardSol, e.g. hold-1k-7d:1000:7:1)`);
    return { id, mcapSol, days, rewardSol };
  });
  if (new Set(out.map((x) => x.id)).size !== out.length) throw new Error("duplicate milestone id");
  return out;
}

export interface MilestoneDay { day: string; minMcapSol: number; samples: number }
export interface MilestoneProgress { id: string; mcapSol: number; days: number; rewardSol: number; streak: number; qualified: boolean; qualifiedDay: string | null; broken: number }

/** Count consecutive full UTC days strictly after the migration day whose LOWEST sampled mcap is >= the threshold.
 *  A day below the threshold resets the streak; a day with fewer than `minSamples` samples (tracker down) is skipped,
 *  neither counting nor breaking. Once `days` is reached the milestone is qualified for good (qualifiedDay = the day it completed).
 *  `days` must be sorted ascending and only contain CLOSED days (the open day is never counted). */
export function milestoneProgress(m: Milestone, migratedDay: string, days: MilestoneDay[], minSamples = 1): MilestoneProgress {
  let streak = 0, broken = 0;
  for (const d of days) {
    if (d.day <= migratedDay || d.samples < minSamples) continue;
    if (d.minMcapSol >= m.mcapSol) { streak++; if (streak >= m.days) return { ...m, streak, qualified: true, qualifiedDay: d.day, broken }; }
    else { if (streak) broken++; streak = 0; }
  }
  return { ...m, streak, qualified: false, qualifiedDay: null, broken };
}
